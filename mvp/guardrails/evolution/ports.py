"""Dependency boundaries: domain code does not import web or database adapters."""

from __future__ import annotations

from collections.abc import Callable
from contextlib import AbstractContextManager
from datetime import datetime
from typing import Any, Protocol

from .models import (
    Capability,
    ContentPart,
    Decision,
    EvaluationRequest,
    Finding,
    JsonObject,
    PolicyRef,
    PolicyVersion,
    Rule,
    Stage,
)


class ClockPort(Protocol):
    def now(self) -> datetime: ...
    def monotonic(self) -> float: ...


class EvaluatorPort(Protocol):
    def capabilities(self) -> tuple[Capability, ...]: ...
    async def evaluate(self, rule: Rule, parts: tuple[ContentPart, ...], deadline_monotonic: float) -> tuple[Finding, ...]: ...
    async def close(self) -> None: ...


class ConnectorPort(Protocol):
    def normalize(self, payload: JsonObject, stage: Stage) -> EvaluationRequest: ...
    def enforce(self, decision: Decision, payload: JsonObject) -> JsonObject: ...


class PolicyResolver(Protocol):
    def get_policy(self, reference: PolicyRef) -> PolicyVersion: ...


class PublishedBaselinePort(Protocol):
    """The only permitted reader of published platform policy bytes."""

    def get_policy(self, reference: PolicyRef) -> PolicyVersion: ...


class TransactionPort(Protocol):
    def get(self, kind: str, key: str, *, required: bool = False, for_update: bool = False) -> dict[str, Any] | None: ...
    def insert(self, kind: str, key: str, data: Any, *, immutable: bool = False, audit_sequence: int | None = None) -> dict[str, Any]: ...
    def put(self, kind: str, key: str, data: Any, *, expected_revision: int) -> dict[str, Any]: ...
    def list(self, kind: str, *, limit: int = 100, after: str | None = None) -> list[dict[str, Any]]: ...
    def append(self, kind: str, data: Any, *, key: str | None = None) -> dict[str, Any]: ...
    def lock(self, key: str) -> None: ...
    def lock_governance(self, *, exclusive: bool = False) -> None: ...
    def page(self, kind: str, *, limit: int = 50, after: tuple[str, str] | None = None, filters: dict | None = None) -> list[dict[str, Any]]: ...
    def next_version(self, kind: str, resource_id: str) -> int: ...
    def link(self, source_kind: str, source_key: str, target_kind: str, target_key: str) -> None: ...
    def cas_binding(self, workload_id: str, expected_revision: int, binding: dict[str, Any]) -> dict[str, Any]: ...


class TenantRepositoryPort(Protocol):
    def transaction(self, tenant_id: str) -> AbstractContextManager[TransactionPort]: ...


class TransformationPort(Protocol):
    def transform(self, parts: tuple[ContentPart, ...], findings: tuple[Finding, ...]) -> tuple[ContentPart, ...]: ...


PolicyLookup = PolicyResolver | Callable[[PolicyRef], PolicyVersion]
